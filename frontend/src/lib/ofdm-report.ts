export interface OfdmReport {
	protocol: 'ofdm-web-verified-v1';
	approved_report: string;
	content_sha256: string;
	delivery_id: string;
	report_id: string;
	session_id: string;
	experiment_binding: { name: string; slug: string; started_at: string; identity_sha256: string } | null;
}

/** Legacy reports omit blank lines around pipe tables. Format only the view. */
export function reportMarkdownForDisplay(text: string): string {
	const lines: string[] = [];
	let fence = '';
	let previous = '';
	for (const line of text.split('\n')) {
		const marker = line.match(/^\s*(`{3,}|~{3,})/)?.[1];
		if (!fence && line.trim() && previous.trim() &&
			line.trimStart().startsWith('|') !== previous.trimStart().startsWith('|')) {
			lines.push('');
		}
		lines.push(line);
		if (marker) {
			if (!fence) fence = marker;
			else if (marker[0] === fence[0] && marker.length >= fence.length) fence = '';
		}
		previous = line;
	}
	return lines.join('\n');
}

/** This record is generated by the platform, never by model-authored prose. */
export function parseOfdmReport(value: unknown): OfdmReport {
	const r = value as Partial<OfdmReport> | null;
	if (!r || r.protocol !== 'ofdm-web-verified-v1' || typeof r.approved_report !== 'string' ||
		!r.approved_report || !/^[a-f0-9]{64}$/.test(r.content_sha256 ?? '') ||
		!/^[a-f0-9]{64}$/.test(r.delivery_id ?? '') || typeof r.report_id !== 'string' ||
		typeof r.session_id !== 'string' || (r.experiment_binding !== null &&
		(!r.experiment_binding || typeof r.experiment_binding.name !== 'string' ||
		 typeof r.experiment_binding.slug !== 'string' ||
		 typeof r.experiment_binding.started_at !== 'string' ||
		 !/^[a-f0-9]{64}$/.test(r.experiment_binding.identity_sha256)))) {
		throw new Error('报告校验数据不完整，已阻止展示。');
	}
	return r as OfdmReport;
}

export async function verifyOfdmReport(report: OfdmReport): Promise<void> {
	const bytes = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(report.approved_report));
	const hash = Array.from(new Uint8Array(bytes), (b) => b.toString(16).padStart(2, '0')).join('');
	if (hash !== report.content_sha256) throw new Error('报告正文 SHA-256 不匹配，已阻止展示。');
	if (report.experiment_binding) {
		const { name, slug, started_at, identity_sha256 } = report.experiment_binding;
		const data = new TextEncoder().encode(JSON.stringify({ name, slug, started_at }));
		const digest = await crypto.subtle.digest('SHA-256', data);
		const actual = Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, '0')).join('');
		if (actual !== identity_sha256) throw new Error('报告实验身份 SHA-256 不匹配。');
	}
}
